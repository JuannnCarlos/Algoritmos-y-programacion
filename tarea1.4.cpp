#include <iostream>
using namespace std;

//imprimir los numeros del 1 al 10
// utilizando while

int main()
{
    int cont = 1; 

    while (cont <= 10) { 
        cout << cont << endl;
        cont = cont + 1; 
    }

    return 0;
}